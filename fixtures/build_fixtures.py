from __future__ import annotations

"""Build the demo documents. Each is a synthetic bill for a fictional issuer, plus a plain-text
transcription so the pipeline can be tested without a camera. Nothing here imitates a real company.
"""
import json
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

OUT = Path(__file__).resolve().parent
W, H = 900, 1180
INK = (24, 24, 27)
MUTED = (95, 95, 105)
PAPER = (252, 251, 247)


def font(size: int, bold: bool = False):
    candidates = [
        "/System/Library/Fonts/Supplemental/Courier New Bold.ttf" if bold else "/System/Library/Fonts/Supplemental/Courier New.ttf",
        "/System/Library/Fonts/Menlo.ttc",
        "/Library/Fonts/Arial.ttf",
    ]
    for path in candidates:
        try:
            return ImageFont.truetype(path, size)
        except OSError:
            continue
    return ImageFont.load_default()


def sheet():
    img = Image.new("RGB", (W, H), PAPER)
    return img, ImageDraw.Draw(img)


def wrap(draw, text, x, y, max_width, f, fill=INK, leading=1.5):
    words, line = text.split(), ""
    for word in words:
        trial = f"{line} {word}".strip()
        if draw.textlength(trial, font=f) > max_width and line:
            draw.text((x, y), line, font=f, fill=fill)
            y += int(f.size * leading)
            line = word
        else:
            line = trial
    if line:
        draw.text((x, y), line, font=f, fill=fill)
        y += int(f.size * leading)
    return y


