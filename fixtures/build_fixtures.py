    d.text((48, 80), "Billing department  |  sunrisehospital.demo", font=small, fill=MUTED)
    y = 136
    d.text((48, y), "Pre-authorisation query", font=font(20, True), fill=INK)
    d.text((W - 320, y), "Ref SH/PA/4471", font=mono, fill=INK)
    y += 40
    y = wrap(d, "Your insurer has asked for the discharge summary and the itemised bill before it will settle claim 4471. "
                "Please send both to billing@sunrisehospital.demo within seven days. No payment is due from you at this stage.",
            48, y, W - 96, body)
    y += 30
    y = wrap(d, "If the documents are not received by 18 Nov 2026, the pre-authorisation lapses and the claim will be closed.",
             48, y, W - 96, body)
    y += 60
    d.text((48, y), "Documents required", font=font(18, True), fill=INK)
    y += 34
    for item in ["Discharge summary", "Itemised bill", "Investigation reports", "Insurance card copy"]:
        d.text((60, y), "- " + item, font=body, fill=INK)
        y += 28
    y += 40
    d.text((48, y), "This letter is synthetic and exists to test a document that asks for no money.", font=small, fill=MUTED)
    return img


